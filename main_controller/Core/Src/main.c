/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM1_Init();
  MX_TIM2_Init();
  MX_TIM3_Init();
  MX_SPI1_Init();
  MX_I2C1_Init();
  /* USER CODE BEGIN 2 */

  /* Start the quadrature encoder interfaces. CubeMX configures the timers but
   * does not start them, so without this the counters never move. */
  HAL_TIM_Encoder_Start(&htim1, TIM_CHANNEL_ALL);   /* right encoder */
  HAL_TIM_Encoder_Start(&htim2, TIM_CHANNEL_ALL);   /* left encoder  */

  /* Start the four motor PWM channels (2 per motor, IN/IN drive mode). */
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_1);   /* RM_PWM_INA */
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_2);   /* RM_PWM_INB */
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_3);   /* LM_PWM_INA */
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_4);   /* LM_PWM_INB */

  /* Make sure nothing is driven until a test asks for it. */
  Motor_Brake();

  /* Microsecond timebase for the EKF prediction step. Must come before any
   * controller init, since TurnController_Init() times its gyro calibration
   * with it. */
  DWT_Timer_Init();

  /* CubeMX drives IMU_NCS LOW in MX_GPIO_Init(), but SPI chip select must
   * IDLE HIGH or the first transaction is framed wrong. Deassert it before
   * talking to the IMU. */
  HAL_GPIO_WritePin(IMU_NCS_GPIO_Port, IMU_NCS_Pin, GPIO_PIN_SET);
  HAL_Delay(50);

  /* Bring up both controllers. Each pulls its gains from control_config.h.
   * Both call Encoders_Init() and MotorDriver_Enable() internally, which is
   * idempotent, so initialising both here is safe.
   *
   * TurnController_Init() also brings up the IMU and runs the stationary gyro
   * bias calibration, so THE ROBOT MUST BE STILL AND LEVEL AT POWER-ON. */
  StraightlineController_Init();
  tm_imu_ok = TurnController_Init();

  /* Startup indication.
   *   3 slow blinks           = IMU up, bias calibrated, fusion active
   *   3 slow THEN 6 fast      = IMU up but bias calibration was REJECTED.
   *                             Turns still run, but on an unestimated gyro
   *                             bias. Read turn_bias_cal_status for the
   *                             reason (moved during calibration vs. a
   *                             failed gyro read).
   *   6 fast blinks           = IMU not found, running encoder-only */
  if (tm_imu_ok) {
    LED_Blink(3, 300, 300);

    if (!TurnController_IsBiasCalibrated()) {
      LED_Blink(6, 80, 80);
    }
  }
  else {
    LED_Blink(6, 80, 80);
  }

  tm_gyro_bias_dps = TurnController_GetGyroBiasDps();

  /* Bring up the TCA9548A mux and the three VL53L0X ranging sensors.
   *
   * This takes noticeably longer than the other peripherals: each sensor runs
   * reference SPAD management and VHV/phase calibration, so budget ~50-100 ms
   * per sensor.
   *
   * Like the IMU, a failure here is NOT fatal. Nothing in the motion
   * controllers consumes range data yet, so a dead sensor must not stop the
   * robot from driving. 2 fast blinks flags it; tm_tof_ready says which
   * sensors actually came up. */
  if (ToF_Init() != TOF_OK) {
    LED_Blink(2, 80, 80);
  }

  TestHarness_CaptureToFReady();

  /* Settling delay so the robot is not already moving when you take your
   * hand off it. */
  HAL_Delay(2000);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */

    /* Runs whichever test ACTIVE_TEST selects (test_harness.h), including
     * its cycle pause. See test_harness.c for the dispatch and routines. */
    TestHarness_RunCycle();
  }
  /* USER CODE END 3 */
}

